<?php

namespace Kirby\Archive;

use Closure;
use Kirby\Cms\App;
use Kirby\Data\Json;
use Kirby\Filesystem\Dir;
use Kirby\Filesystem\F;

/**
 * Crawls the site into static files with
 * an nginx config, e.g. for archived docs
 */
class Snapshot
{
	public Crawler $crawler;

	public function __construct(
		protected string $url,
		protected string $root,
		protected array $include = [],
		protected string $fallback = 'https://getkirby.com',
		protected int $workers = 8
	) {
	}

	/**
	 * Crawls the site running at the origin, starting
	 * from the given paths or all pages of the site
	 */
	public function crawl(
		string $origin,
		array|null $paths = null,
		Closure|null $progress = null
	): Crawler {
		$this->crawler = new Crawler(
			origin: $origin,
			root: $this->root . '/public',
			url: $this->url,
			include: $this->include,
			workers: $this->workers
		);

		$this->crawler->crawl($this->seeds($origin, $paths), $progress);

		return $this->crawler;
	}

	/**
	 * Returns the nginx config of the site in Ploi
	 */
	public function nginx(): string
	{
		$host      = parse_url($this->url, PHP_URL_HOST);
		$redirects = '';

		foreach ($this->redirects() as $path => $location) {
			$redirects .= "\t" . 'location = "' . $path . '" { return 301 "' . $location . '"; }' . PHP_EOL;
		}

		return <<<NGINX
			# Generated by `kirby archive:snapshot`: upload the `public` folder,
			# e.g. with `rsync -az public/ archive@server:/home/archive/{$host}/`,
			# and replace the nginx config of the site in Ploi with this file

			# Ploi Webserver Configuration, do not remove!
			include /etc/nginx/ploi/{$host}/before/*;

			server {
				root /home/archive/{$host}/;
				server_name {$host};

				include /etc/nginx/ssl/{$host};

				ssl_protocols TLSv1.2 TLSv1.3;
				ssl_ciphers 'ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305:ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:DHE-RSA-AES128-GCM-SHA256:DHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-AES128-SHA256:ECDHE-RSA-AES128-SHA256:ECDHE-ECDSA-AES128-SHA:ECDHE-RSA-AES256-SHA384:ECDHE-RSA-AES128-SHA:ECDHE-ECDSA-AES256-SHA384:ECDHE-ECDSA-AES256-SHA:ECDHE-RSA-AES256-SHA:DHE-RSA-AES128-SHA256:DHE-RSA-AES128-SHA:DHE-RSA-AES256-SHA256:DHE-RSA-AES256-SHA:ECDHE-ECDSA-DES-CBC3-SHA:ECDHE-RSA-DES-CBC3-SHA:EDH-RSA-DES-CBC3-SHA:AES128-GCM-SHA256:AES256-GCM-SHA384:AES128-SHA256:AES256-SHA256:AES128-SHA:AES256-SHA:DES-CBC3-SHA:!DSS';
				ssl_prefer_server_ciphers on;
				ssl_dhparam /etc/nginx/dhparams.pem;

				add_header X-Frame-Options "SAMEORIGIN";
				add_header Strict-Transport-Security "max-age=31536000; includeSubDomains";
				add_header X-Content-Type-Options "nosniff";

				charset utf-8;
				absolute_redirect off;

				# Ploi Configuration, do not remove!
				include /etc/nginx/ploi/{$host}/server/*;

				# clean URLs: /docs/guide -> /docs/guide/index.html
				location / {
					try_files \$uri \$uri/index.html @fallback;
				}

				# anything not in the snapshot is looked up on the current site
				location @fallback {
					return 302 {$this->fallback}\$request_uri;
				}

				# redirects recorded while crawling
			{$redirects}
				access_log off;
				error_log  /var/log/nginx/{$host}-error.log error;

				location = /favicon.ico { access_log off; log_not_found off; }
				location = /robots.txt  { access_log off; log_not_found off; }

				location ~ /\.(?!well-known).* {
					deny all;
				}
			}

			# Ploi Webserver Configuration, do not remove!
			include /etc/nginx/ploi/{$host}/after/*;

			NGINX;
	}

	/**
	 * Returns the recorded redirects by path,
	 * except those the fallback handles anyway
	 */
	public function redirects(): array
	{
		$redirects = [];

		foreach ($this->crawler->results as $url => $result) {
			if (isset($result['location']) === false) {
				continue;
			}

			$path     = rawurldecode(parse_url($url, PHP_URL_PATH) ?: '/');
			$location = $this->crawler->rewrite($result['location']);
			$location = str_replace($this->url, '', $location) ?: '/';

			if ($location !== $this->fallback . $path) {
				$redirects[$path] = $location;
			}
		}

		ksort($redirects);

		return $redirects;
	}

	/**
	 * Returns the URLs to start crawling from: the
	 * given paths or URLs or all pages of the site
	 */
	public function seeds(string $origin, array|null $paths = null): array
	{
		$paths ??= App::instance()->site()->index()->values(
			fn ($page) => $page->isHomePage() === true ? '/' : $page->uri()
		);

		$urls = [$origin . '/robots.txt'];

		foreach ($paths as $path) {
			$urls[] = $origin . '/' . ltrim(parse_url($path, PHP_URL_PATH) ?? '', '/');
		}

		return $urls;
	}

	/**
	 * Returns how often each linked path
	 * that isn't in the snapshot is linked to
	 */
	public function unresolved(): array
	{
		$public     = $this->root . '/public';
		$redirects  = $this->redirects();
		$exists     = [];
		$unresolved = [];

		foreach (Dir::index($public, true) as $path) {
			if (basename($path) !== 'index.html') {
				continue;
			}

			$page = rtrim($this->url . '/' . dirname($path), '/.');

			foreach (Crawler::links(F::read($public . '/' . $path), 'html') as $link) {
				$link = Crawler::resolve($page, $link);

				if (str_starts_with($link, $this->url . '/') === false) {
					continue;
				}

				$target = rawurldecode(parse_url($link, PHP_URL_PATH));

				$exists[$target] ??=
					isset($redirects[$target]) === true ||
					is_file($public . $target) === true ||
					is_file($public . rtrim($target, '/') . '/index.html') === true;

				if ($exists[$target] === false) {
					$unresolved[$target] = ($unresolved[$target] ?? 0) + 1;
				}
			}
		}

		arsort($unresolved);

		return $unresolved;
	}

	/**
	 * Writes the nginx config and the report
	 * of the crawl and returns the report
	 */
	public function write(): array
	{
		$report = [
			'errors'     => array_filter(
				$this->crawler->results,
				fn ($result) => $result['status'] === 0 || $result['status'] >= 400
			),
			'redirects'  => $this->redirects(),
			'unresolved' => $this->unresolved(),
			'queries'    => $this->crawler->queries
		];

		F::write($this->root . '/nginx.conf', $this->nginx());
		Json::write($this->root . '/report.json', $report);

		return $report;
	}
}
